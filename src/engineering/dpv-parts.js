/** Attach viewer groups and semantics to a parsed DPV GLB model. */
export function annotateDpv(model){
 const byNode=new Map(DPV_PARTS.map(p=>[p.node,p]));
 for(const c of model.components){
  const part=byNode.get(c.sourceObjectId);
  if(!part)continue;
  c.metadata={...c.metadata,viewerGroup:part.viewerGroup,semantic:part.semantic};
 }
 return model;
}
